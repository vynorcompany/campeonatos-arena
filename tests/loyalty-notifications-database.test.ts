import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import test from "node:test";
import { PrismaClient, type Prisma } from "@prisma/client";
import { instantToArenaWallClock } from "../src/lib/calendar/arena-wall-clock";
import { syncClientLoyaltyNotifications, loyaltyNotificationType } from "../src/lib/services/client-loyalty-notifications";
import { loadClientLoyalty } from "../src/lib/services/client-loyalty";

const url = process.env.ARENA_GOAL_TEST_DATABASE_URL ?? "";
const local = /^postgresql:\/\/postgres@127\.0\.0\.1:55433\/arena_goal(?:\?|$)/.test(url);
test("fidelidade avisa uma vez por meta, conta somente visitas válidas, preserva leitura e encerra alertas após resgate", { skip: !local }, async () => {
  const admin = new PrismaClient({ datasources: { db: { url } } });
  const runtimeUrl = new URL(url); runtimeUrl.username = "arena_runtime";
  const runtime = new PrismaClient({ datasources: { db: { url: runtimeUrl.toString() } } });
  const arenaIds: string[] = [];
  const suffix = randomUUID();
  const now = new Date("2030-02-01T12:00:00Z");
  const startedAt = new Date("2030-01-01T12:00:00Z");
  const scoped = <T>(id: string, fn: (tx: Prisma.TransactionClient) => Promise<T>) => runtime.$transaction(async tx => { await tx.$executeRaw`SELECT set_config('app.arena_id', ${id}, true)`; return fn(tx); });
  try {
    const owner = await admin.user.findUniqueOrThrow({ where: { id: "goal-test" }, select: { id: true } });
    for (const label of ["A", "B"]) arenaIds.push((await admin.arena.create({ data: { createdById: owner.id, name: `Fidelidade ${label} ${suffix}`, slug: `loyalty-${label}-${suffix}`, loyaltyEnabled: true, loyaltyStartedAt: startedAt, loyaltyVisitsRequired: 5, loyaltyRewardLabel: "Uma hora de quadra" } })).id);
    const [a, b] = arenaIds;
    const player = await admin.player.create({ data: { arenaId: a, name: "Cliente elegível" } });
    const future = await admin.player.create({ data: { arenaId: a, name: "Visita ainda em andamento" } });
    const inactive = await admin.player.create({ data: { arenaId: a, name: "Cliente inativo", active: false } });
    const foreign = await admin.player.create({ data: { arenaId: b, name: "Cliente de outra arena" } });
    const visit = (playerId: string, arenaId: string, visitsDelta: number, kind = "VISIT") => admin.loyaltyActivity.create({ data: { arenaId, playerId, kind, visitsDelta, createdByUserId: "qa-loyalty", createdAt: new Date("2030-01-15T12:00:00Z") } });
    const reservation = (playerId: string, endsAt: Date, data: { status?: string; sourceType?: string; bookingTypeName?: string } = {}) => admin.scheduleOccurrence.create({ data: { arenaId: a, title: "Reserva de teste de fidelidade", sourceType: "BOOKING", bookingTypeName: "Reserva", status: "SCHEDULED", ...data, endsAt: instantToArenaWallClock(endsAt), startsAt: instantToArenaWallClock(new Date(endsAt.getTime() - 3600000)), participants: { create: { playerId } } } });
    for (const day of [10, 11, 12]) await reservation(player.id, new Date(`2030-01-${day}T12:00:00Z`));
    await reservation(player.id, new Date("2029-12-31T12:00:00Z"));
    await reservation(player.id, new Date("2030-01-13T12:00:00Z"), { status: "CANCELLED" });
    await reservation(player.id, new Date("2030-01-14T12:00:00Z"), { bookingTypeName: "Aula" });
    await reservation(player.id, new Date("2030-01-16T12:00:00Z"), { sourceType: "LESSON" });
    await visit(player.id, a, 2);
    await visit(future.id, a, 4);
    await reservation(future.id, new Date(now.getTime() + 60000));
    await visit(inactive.id, a, 5);
    await visit(foreign.id, b, 5);
    // Even inconsistent legacy cross-arena participants cannot leak into this arena's alerts.
    await reservation(foreign.id, new Date("2030-01-17T12:00:00Z"));
    const state = await scoped(a, tx => loadClientLoyalty(tx, a, player.id, now));
    assert.equal(state.availableVisits, 5);
    assert.equal(state.availableRewards, 1);
    await Promise.all(Array.from({ length: 3 }, () => scoped(a, tx => syncClientLoyaltyNotifications(tx, a, now))));
    let notices = await admin.arenaNotification.findMany({ where: { arenaId: a, type: loyaltyNotificationType } });
    assert.equal(notices.length, 1);
    assert.match(notices[0].message, /Cliente elegível.*1 recompensa disponível/);
    assert.ok(notices[0].href.includes(encodeURIComponent(player.name)));
    assert.equal(await admin.arenaNotification.count({ where: { arenaId: b } }), 0);
    await admin.arenaNotification.update({ where: { id: notices[0].id }, data: { readAt: now } });
    await scoped(a, tx => syncClientLoyaltyNotifications(tx, a, now));
    assert.ok((await admin.arenaNotification.findUniqueOrThrow({ where: { id: notices[0].id } })).readAt);
    assert.equal(await admin.arenaNotification.count({ where: { arenaId: a, readAt: null } }), 0);
    const later = new Date(now.getTime() + 120000);
    await scoped(a, tx => syncClientLoyaltyNotifications(tx, a, later));
    assert.equal(await admin.arenaNotification.count({ where: { arenaId: a, readAt: null } }), 1);
    await visit(player.id, a, 5);
    await scoped(a, tx => syncClientLoyaltyNotifications(tx, a, later));
    notices = await admin.arenaNotification.findMany({ where: { arenaId: a, readAt: null } });
    assert.equal(notices.length, 2);
    const earned = notices.find(n => n.message.includes(player.name))!;
    assert.match(earned.message, /2 recompensas disponíveis/);
    await visit(player.id, a, -5, "REWARD");
    await scoped(a, tx => syncClientLoyaltyNotifications(tx, a, later));
    assert.match((await admin.arenaNotification.findUniqueOrThrow({ where: { id: earned.id } })).message, /1 recompensa disponível/);
    await visit(player.id, a, -5, "REWARD");
    await scoped(a, tx => syncClientLoyaltyNotifications(tx, a, later));
    assert.ok((await admin.arenaNotification.findUniqueOrThrow({ where: { id: earned.id } })).readAt);
    await scoped(b, tx => syncClientLoyaltyNotifications(tx, b, later));
    assert.equal(await admin.arenaNotification.count({ where: { arenaId: b, readAt: null } }), 1);
    await admin.arena.update({ where: { id: a }, data: { loyaltyEnabled: false } });
    await scoped(a, tx => syncClientLoyaltyNotifications(tx, a, later));
    assert.equal(await admin.arenaNotification.count({ where: { arenaId: a, readAt: null } }), 0);
    assert.equal(await admin.arenaNotification.count({ where: { arenaId: b, readAt: null } }), 1);
  } finally {
    await admin.scheduleOccurrence.deleteMany({ where: { arenaId: { in: arenaIds } } });
    await admin.player.deleteMany({ where: { arenaId: { in: arenaIds } } });
    await admin.arena.deleteMany({ where: { id: { in: arenaIds } } });
    await runtime.$disconnect(); await admin.$disconnect();
  }
});
